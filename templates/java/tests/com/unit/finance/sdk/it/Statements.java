package com.unit.finance.sdk.it;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import java.io.IOException;
import java.util.Collections;

/**
 * Statement helpers, mirroring the Node {@code tests/helpers/statements.ts}.
 */
final class Statements {

  /**
   * The spec names this resource {@code statement}; the sandbox answers with
   * {@code accountStatementDTO}. Spec defect owned by {@code unit-openapi}.
   */
  static final String STATEMENT_TYPE = "accountStatementDTO";

  private Statements() {}

  /**
   * The raw JSON:API list of statements.
   *
   * <p>The typed call cannot be used: the generated {@code Statement} model
   * pins {@code type} to the spec's {@code statement} enum and gson rejects the
   * {@code accountStatementDTO} the sandbox actually sends.
   */
  static JsonArray listStatementsRaw() throws IOException {
    // Because the response is unpaged it is slow enough that the sandbox
    // intermittently fails to produce it at all: sometimes a gateway gives up
    // and answers 5xx with a non-JSON error page, sometimes nothing arrives
    // before the read timeout. Both are retried, for the same reason the Node
    // provisioning helpers are — resolving a statement id is setup for the
    // download suites, not the operation they assert.
    Exception last = null;
    for (int attempt = 1; attempt <= 3; attempt++) {
      try {
        JsonObject body =
            ApiSupport.rawGet(
                "/statements",
                Collections.singletonMap("page[limit]", "20"),
                ApiSupport.STATEMENTS_READ_TIMEOUT_MS);
        int status = ApiSupport.rawStatus(body);
        if (status == 200 && !body.has("__body")) {
          JsonArray data = body.getAsJsonArray("data");
          return data == null ? new JsonArray() : data;
        }
        last =
            new IllegalStateException(
                "expected status 200 and a JSON body, got "
                    + status
                    + " "
                    + ApiSupport.rawBodyText(body));
      } catch (IOException e) {
        last = e;
      }
      try {
        ApiSupport.sleep(1000L * (1L << (attempt - 1)));
      } catch (InterruptedException e) {
        Thread.currentThread().interrupt();
        break;
      }
    }
    throw new IOException("Failed to list statements: " + last.getMessage(), last);
  }

  /** Memoizes {@link #getStatementId}; surefire runs every IT in one JVM. */
  private static boolean idResolved;

  private static String cachedId;

  /**
   * A statement id, or {@code null} when one cannot be obtained.
   *
   * <p>Statements are generated by Unit at the close of each monthly period;
   * there is no operation to mint one. A freshly provisioned sandbox account
   * therefore has no statement at all, which makes the per-statement PDF / HTML
   * reads unreachable rather than broken.
   *
   * <p>A list read that fails outright is treated the same way. The cost of the
   * unpaged response is not bounded by anything we control — on CI it has
   * exceeded even the 180s budget of {@link ApiSupport#STATEMENTS_READ_TIMEOUT_MS}
   * — and an id the sandbox will not hand over leaves the download operation
   * just as unreachable. {@link #listStatementsRaw} stays strict for
   * {@code ListStatementsIT}, which asserts the list itself.
   */
  static String getStatementId() {
    if (idResolved) {
      return cachedId;
    }
    idResolved = true;
    try {
      for (JsonElement element : listStatementsRaw()) {
        JsonObject statement = element.getAsJsonObject();
        if (statement.has("id")) {
          cachedId = statement.get("id").getAsString();
          return cachedId;
        }
      }
      System.out.println(
          "This sandbox org has no statements (they are generated monthly and cannot be "
              + "created from the API); skipping.");
    } catch (IOException e) {
      System.out.println(
          "Could not resolve a statement id from the sandbox, so the download is "
              + "unreachable; skipping. "
              + e.getMessage());
    }
    return null;
  }
}
