"""Statement helpers, the Python analogue of Node's ``helpers/statements.ts``."""

import json
from typing import Any, Dict, List, Optional

from .api import build_statements_api

# The spec names this resource ``statement``; the sandbox answers with
# ``accountStatementDTO``. Spec defect owned by ``unit-openapi``.
STATEMENT_TYPE = "accountStatementDTO"


def list_statements_raw() -> List[Dict[str, Any]]:
    """The raw JSON:API list of statements.

    The typed call cannot be used: the generated ``Statement`` model pins
    ``type`` to the spec's ``statement`` enum and pydantic rejects the
    ``accountStatementDTO`` the sandbox actually sends.
    """
    response = build_statements_api().list_statements_without_preload_content(
        page_limit="20"
    )
    body = json.loads(response.read())
    if response.status != 200:
        raise RuntimeError(
            f"Failed to list statements: expected status 200, got {response.status}."
        )
    return list(body.get("data") or [])


def get_statement_id() -> Optional[str]:
    """A statement id, or ``None`` when the org has none.

    Statements are generated by Unit at the close of each monthly period; there
    is no operation to mint one. A freshly provisioned sandbox account therefore
    has no statement at all, which makes the per-statement PDF / HTML reads
    unreachable rather than broken.
    """
    for statement in list_statements_raw():
        statement_id = statement.get("id")
        if isinstance(statement_id, str):
            return statement_id
    print(
        "This sandbox org has no statements (they are generated monthly and "
        "cannot be created from the API); skipping."
    )
    return None
