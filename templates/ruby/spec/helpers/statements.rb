# Statement helpers, the Ruby analogue of Node's `helpers/statements.ts` and
# Python's `helpers/statements.py`.

require 'json'
require_relative 'api'

module Helpers
  module Statements
    # The spec names this resource `statement`; the sandbox answers with
    # `accountStatementDTO`. Spec defect owned by `unit-openapi`.
    TYPE = 'accountStatementDTO'.freeze

    module_function

    # The raw JSON:API list of statements.
    #
    # The typed call cannot be used: the generated `Statement` model pins
    # `type` to the spec's `statement` enum and its writer raises on the
    # `accountStatementDTO` the sandbox actually sends.
    def list_raw(page_limit = '20')
      api = Helpers::Api.build_statements_api
      body, status_code, = api.list_statements_with_http_info(
        page_limit: page_limit, debug_return_type: 'String'
      )
      raise "Failed to list statements: expected status 200, got #{status_code}." unless status_code == 200

      [Array(JSON.parse(body)['data']), status_code]
    end

    # A statement id, or nil when the org has none.
    #
    # Statements are generated by Unit at the close of each monthly period;
    # there is no operation to mint one. A freshly provisioned sandbox account
    # therefore has no statement at all, which makes the per-statement PDF /
    # HTML reads unreachable rather than broken.
    def id_or_skip
      statements, = list_raw('1')
      first = statements.first
      if first.nil?
        warn 'This sandbox org has no statements (they are generated monthly ' \
             'and cannot be created from the API); skipping.'
        return nil
      end
      first['id']
    end
  end
end
