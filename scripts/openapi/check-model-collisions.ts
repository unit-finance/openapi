#!/usr/bin/env tsx
/**
 * check-model-collisions.ts
 *
 * Fails the pipeline when two schemas would generate the same model class name.
 *
 * `fetch-spec` already renames the case we know how to predict — inline request
 * bodies — but openapi-generator invents model names for far more than that:
 * responses, array items (`_inner`), composition branches (`_oneOf`, `_allOf`),
 * and nested inline properties. Rather than reimplement all of those naming
 * rules and hope the list stays complete, this check asks the generator itself:
 * `InlineModelResolver` logs a line for every synthetic model it creates, so a
 * dry run enumerates them exactly.
 *
 * Without this, a collision is not a clean failure. Ruby dies with a 1000-frame
 * `StackOverflowError` pointing at a line of generator internals, and
 * typescript-axios doesn't fail at all — it emits `export type X = X | Y` and
 * defers the breakage to whenever someone next compiles the SDK. See
 * `model-names.ts` for why.
 *
 * Usage: `npm run check-model-collisions` (runs automatically in the
 * `generate-sdks` pipeline, right after the spec is materialized).
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { toClassName } from "./model-names";

const REPO_ROOT = process.cwd();
const SPEC_PATH = path.join(REPO_ROOT, "spec", "openapi.bundled.json");

/** Matches the InlineModelResolver log line announcing a synthetic model. */
const INLINE_SCHEMA_LOG = /Inline schema created as ([^.\s]+)\./g;

/**
 * Enumerate the synthetic model keys the generator would create for this spec,
 * by running a dry-run generation and reading its own log. Language choice is
 * immaterial: InlineModelResolver runs before any language-specific templating,
 * so the names it reports are the same for all four SDKs.
 */
function inlineSchemaKeys(): string[] {
	const outDir = fs.mkdtempSync(path.join(os.tmpdir(), "collision-check-"));
	try {
		const res = spawnSync(
			"npx",
			[
				"--no-install",
				"openapi-generator-cli",
				"generate",
				"--dry-run",
				"-i",
				SPEC_PATH,
				"-g",
				"typescript-axios",
				"-o",
				outDir,
				"-c",
				path.join("templates", "node", "config.json"),
			],
			{ cwd: REPO_ROOT, encoding: "utf8", env: { ...process.env, TZ: "UTC" } },
		);
		const log = `${res.stdout ?? ""}${res.stderr ?? ""}`;
		if (res.status !== 0) {
			throw new Error(
				`dry-run generation failed (exit ${res.status}):\n${log.split("\n").slice(-20).join("\n")}`,
			);
		}
		return [...log.matchAll(INLINE_SCHEMA_LOG)].map((m) => m[1]);
	} finally {
		fs.rmSync(outDir, { recursive: true, force: true });
	}
}

function namedSchemaKeys(): string[] {
	if (!fs.existsSync(SPEC_PATH)) {
		throw new Error(
			`${path.relative(REPO_ROOT, SPEC_PATH)} not found — run \`npm run fetch-spec\` first.`,
		);
	}
	const doc = JSON.parse(fs.readFileSync(SPEC_PATH, "utf8")) as {
		components?: { schemas?: Record<string, unknown> };
	};
	return Object.keys(doc.components?.schemas ?? {});
}

function main(): void {
	const named = namedSchemaKeys();
	const inline = inlineSchemaKeys();

	// Class name -> the schema keys that produce it. A key can legitimately be
	// reported twice (the resolver reuses identical inline schemas), so dedupe
	// before deciding anything is in conflict.
	const byClassName = new Map<string, Set<string>>();
	for (const key of [...named, ...inline]) {
		const className = toClassName(key);
		const keys = byClassName.get(className) ?? new Set<string>();
		keys.add(key);
		byClassName.set(className, keys);
	}

	const collisions = [...byClassName.entries()]
		.filter(([, keys]) => keys.size > 1)
		.sort(([a], [b]) => a.localeCompare(b));

	if (collisions.length === 0) {
		console.log(
			`[check-model-collisions] OK — ${named.length} named + ${new Set(inline).size} ` +
				"inline schema(s), no model name collisions.",
		);
		return;
	}

	console.error(
		`[check-model-collisions] ${collisions.length} model name collision(s) found.\n`,
	);
	for (const [className, keys] of collisions) {
		console.error(`  class ${className} is generated by:`);
		for (const key of [...keys].sort()) console.error(`    - ${key}`);
	}
	console.error(
		[
			"",
			"Two schemas generating one class name breaks the generators: Ruby",
			"recurses until the JVM stack overflows, and typescript-axios emits a",
			"self-referential type alias that does not compile.",
			"",
			"Fix by giving the inline schema a distinct name. Preferred: set `title`",
			"on it in the unit-openapi spec. If the collision is an inline request",
			"body, `fetch-spec`'s titleCollidingInlineRequestBodies should have",
			"handled it automatically — that it didn't means the collision is a kind",
			"it doesn't model yet, so extend that pass.",
		].join("\n"),
	);
	process.exit(1);
}

try {
	main();
} catch (err) {
	console.error(
		`[check-model-collisions] ${err instanceof Error ? err.message : String(err)}`,
	);
	process.exit(1);
}
